/* ============================================================
 * Dispatch 表 + trie（每个 simd 实例独立一份）
 * ============================================================ */
#define SIMD_NUM_INST 300

typedef struct {
    void  *dispatch[SIMD_NUM_INST];
    int    dispatch_ready;
    DecodeTrie trie;
    opcode_entry_t op_table[SIMD_NUM_INST];
    size_t op_count;
} SIMDDecoder;

/* 初始化 trie（构造函数调用一次） */
static void simd_decoder_init(SIMDDecoder *d) {
    if (d->op_count > 0) return;
    int idx = 0;
    #define X(name, pattern, op_type, imm_fn) \
        d->op_table[idx].mask=pattern_to_mask(pattern),\
        d->op_table[idx].match=pattern_to_match(pattern),\
        d->op_table[idx].exec=NULL,\
        d->op_table[idx].type=op_type,\
        idx++
    { INSTRUCTION_LIST; }
    #undef X
    d->op_count = idx;
    decode_trie_build(&d->trie, d->op_table, d->op_count);
}


